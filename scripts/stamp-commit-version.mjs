#!/usr/bin/env node
/**
 * Stamps the version a commit will ship as onto its subject line.
 *
 *   fix(env): never let the startup check prevent startup [v3.1.7]
 *
 * Runs from prepare-commit-msg, which git calls AFTER pre-commit — so
 * `auto-bump-patch.mjs` has already decided the number and package.json holds
 * the final value by the time this reads it. Doing it the other way round would
 * stamp the previous version onto every bumping commit.
 *
 * Several commits before a push all carry the SAME version, and that is
 * correct rather than a flaw: the bump happens once per push cycle, so they do
 * all ship together as that version. `git log --oneline` then reads as a list
 * of what went out under each number, which is the question this exists to
 * answer — which version is running where, and what is in it.
 *
 * Never blocks a commit. Every failure path exits 0, for the same reason the
 * version bump does: a commit message decoration is not worth losing work over.
 */

import { readFileSync, writeFileSync } from 'node:fs';

const [messageFile, source] = process.argv.slice(2);

try {
    // `merge` and `squash` messages are generated by git and are not ours to
    // rewrite. An amend (`commit`) usually already carries the stamp, and the
    // check below catches it when it does.
    if (source === 'merge' || source === 'squash') process.exit(0);
    if (!messageFile) process.exit(0);

    const { version } = JSON.parse(readFileSync('package.json', 'utf8'));
    if (!version) process.exit(0);

    const raw = readFileSync(messageFile, 'utf8');
    const lines = raw.split(/\r?\n/);

    // The subject is the first line that is neither blank nor a git comment.
    const i = lines.findIndex((l) => l.trim() && !l.startsWith('#'));
    if (i === -1) process.exit(0); // Empty message: the commit is being aborted.

    const subject = lines[i];

    // Idempotent. Amending, or a rebase that replays this hook, must not append
    // a second stamp — and a stamp for a DIFFERENT version is replaced rather
    // than accumulated.
    const stripped = subject.replace(/\s*\[v\d+\.\d+\.\d+\]\s*$/, '');
    lines[i] = `${stripped} [v${version}]`;

    if (lines[i] !== subject) {
        writeFileSync(messageFile, lines.join('\n'));
    }
} catch {
    // Deliberately silent: nothing here is worth interrupting a commit for.
}

process.exit(0);
